/// The reserved argument that carries the trusted task id to the backend.
///
/// The guarded wrapper overwrites it from [`RunScope`] on every call, so the
/// model cannot forge it.
pub const TASK_ID_FIELD: &str = "__dhi_task_id";

/// The reserved argument that carries the per-task MAC.
///
/// [`CodingTools::register_tools`] stamps
/// `HMAC-SHA256(secret, task_id)` from the secret generated by
/// [`CodingTools::new`] and the task id in the [`RunScope`]. A backend built by
/// [`CodingTools::backend`] recomputes the MAC for the task id in the request
/// and accepts only an exact match. It is never shown to the model, so a
/// coding tool registered through the generic
/// [`dhi_agent::guarded_dynamic_tool`] path cannot forge a task scope, and a
/// MAC leaked for task A cannot authorize task B.
pub const SCOPE_MAC_FIELD: &str = "__dhi_scope_mac";

/// HMAC-SHA256, the MAC the wrapper stamps and the backend checks.
type HmacSha256 = Hmac<Sha256>;

/// A fresh 32-byte secret. Two UUID v4 values give 32 random bytes without a
/// new random-number dependency.
fn random_secret() -> [u8; 32] {
    let mut secret = [0_u8; 32];
    secret[..16].copy_from_slice(Uuid::new_v4().as_bytes());
    secret[16..].copy_from_slice(Uuid::new_v4().as_bytes());
    secret
}

/// The MAC of `task_id` under `secret`.
pub(crate) fn task_mac(secret: &[u8; 32], task_id: Uuid) -> String {
    let mut mac = HmacSha256::new_from_slice(secret).expect("HMAC accepts a key of any length");
    mac.update(task_id.as_bytes());
    hex(&mac.finalize().into_bytes())
}

/// Whether `presented` is the MAC of `task_id` under `secret`, compared in
/// constant time by the HMAC implementation.
pub(crate) fn task_mac_matches(secret: &[u8; 32], task_id: Uuid, presented: &str) -> bool {
    let Some(presented) = decode_hex(presented) else {
        return false;
    };
    let mut mac = HmacSha256::new_from_slice(secret).expect("HMAC accepts a key of any length");
    mac.update(task_id.as_bytes());
    mac.verify_slice(&presented).is_ok()
}

/// The lowercase hexadecimal form of `bytes`.
fn hex(bytes: &[u8]) -> String {
    use std::fmt::Write as _;

    let mut text = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        write!(text, "{byte:02x}").expect("writing to a String cannot fail");
    }
    text
}

/// Decodes lowercase or uppercase hexadecimal text, or `None` when it is
/// not an even-length run of hex digits.
fn decode_hex(text: &str) -> Option<Vec<u8>> {
    if !text.len().is_multiple_of(2) {
        return None;
    }
    let bytes = text.as_bytes();
    let mut decoded = Vec::with_capacity(bytes.len() / 2);
    for pair in bytes.as_chunks::<2>().0 {
        let high = hex_digit(pair[0])?;
        let low = hex_digit(pair[1])?;
        decoded.push(high << 4 | low);
    }
    Some(decoded)
}

fn hex_digit(byte: u8) -> Option<u8> {
    match byte {
        b'0'..=b'9' => Some(byte - b'0'),
        b'a'..=b'f' => Some(byte - b'a' + 10),
        b'A'..=b'F' => Some(byte - b'A' + 10),
        _ => None,
    }
}

/// The definition of one coding tool: its name, model-facing description,
/// the JSON schema of its arguments, and the tool's annotations.
#[derive(Debug, Clone, PartialEq)]
pub struct ToolDefinition {
    /// The registered tool name.
    pub name: String,
    /// The description sent to the model.
    pub description: String,
    /// The JSON schema of the tool's arguments.
    pub schema: serde_json::Value,
    /// What calling the tool does to the world, taken from the tool itself.
    pub annotations: ToolAnnotations,
}

/// Owns the task containers and the trusted scope secret for one runtime.
///
/// The facade is the public entry point: it registers the six guarded tools
/// with both scope fields stamped from the dispatch [`RunScope`] and its own
/// secret, and it hands out the only backend that accepts MACs made with that
/// secret. The secret is private: no public accessor exposes it, so a tool
/// registered through the generic [`dhi_agent::guarded_dynamic_tool`] path
/// cannot carry a valid MAC for another task.
pub struct CodingTools {
    containers: Arc<TaskContainers>,
    secret: [u8; 32],
}

impl CodingTools {
    /// A facade over `containers` with a fresh random scope secret.
    pub fn new(containers: Arc<TaskContainers>) -> Self {
        Self {
            containers,
            secret: random_secret(),
        }
    }

    /// The MAC of `task_id`, for crate tests only. It is never sent to the
    /// model and is not part of the public or crate API outside tests.
    #[cfg(test)]
    pub(crate) fn mac(&self, task_id: Uuid) -> String {
        task_mac(&self.secret, task_id)
    }

    /// A backend that accepts only calls carrying this facade's MAC.
    pub fn backend(&self) -> CodingBackend {
        CodingBackend::new(Arc::clone(&self.containers), self.secret)
    }

    /// Registers one guarded [`DynamicTool`] per coding tool on `handle`.
    ///
    /// Every call is routed through `sink` with the [`RunScope`] the runtime
    /// stamped into the dispatch context, the scope's task id, and a MAC
    /// bound to that task id. Registration fails if any of the six names
    /// already exists on `handle`; an existing tool is not overwritten.
    pub fn register_tools(
        &self,
        handle: &ToolServerHandle,
        sink: Arc<dyn ToolSink>,
    ) -> anyhow::Result<Vec<String>> {
        register_guarded_tools(handle, sink, self.secret)
    }
}

/// The six coding tools, defined by `rig-tools`.
///
/// The descriptions, schemas, and annotations are built from the tools' own
/// [`Tool`] implementations, so they cannot drift from what the backend runs.
/// `shell` uses the same configured [`Shell`] template as the backend.
pub fn tool_definitions() -> Vec<ToolDefinition> {
    vec![
        definition_of(Read::default()),
        definition_of(Write::default()),
        definition_of(Edit::default()),
        definition_of(Search::default()),
        definition_of(List::default()),
        definition_of(shell_template()),
    ]
}

/// The one `shell` configuration shared by the model-facing definition and
/// the backend, so the generated description cannot drift from the runtime.
pub(crate) fn shell_template() -> Shell {
    Shell {
        workspace: Arc::new(Local),
        launcher: Launcher::default(),
        live: None,
        spill: None,
        cut: Some(OutputLimit::default()),
        confine: true,
        max_timeout: 600,
        quiet: Duration::from_secs(60),
    }
}

fn definition_of<T: Tool>(tool: T) -> ToolDefinition {
    ToolDefinition {
        name: T::NAME.to_owned(),
        description: tool.description(),
        schema: tool.parameters(),
        annotations: tool.annotations(),
    }
}

/// Registers the six coding tools, refusing to overwrite an existing name.
fn register_guarded_tools(
    handle: &ToolServerHandle,
    sink: Arc<dyn ToolSink>,
    secret: [u8; 32],
) -> anyhow::Result<Vec<String>> {
    let definitions = tool_definitions();
    let toolset = handle.toolset();
    for definition in &definitions {
        if toolset.contains(&definition.name) {
            return Err(anyhow!(
                "coding tool {:?} is already registered on this tool server; refusing to overwrite it",
                definition.name
            ));
        }
    }

    let mut names = Vec::with_capacity(definitions.len());
    for ToolDefinition {
        name,
        description,
        schema,
        annotations,
    } in definitions
    {
        let tool = guarded_tool(
            &name,
            description,
            schema,
            annotations,
            Arc::clone(&sink),
            secret,
        )?;
        handle.add_dynamic_tool(tool);
        names.push(name);
    }
    Ok(names)
}

/// Builds the model-visible door to the guard.
///
/// The callback reads [`RunScope`] from the dispatch context (never from the
/// model's arguments), overwrites both reserved scope fields, and maps the
/// sink outcome exactly as [`dhi_agent::guarded_dynamic_tool`] does:
/// `Allowed` returns output, `Denied` is a permission error carrying the
/// reason, `Pending` is an internal error because approvals must block, and
/// any sink failure is a tool error.
fn guarded_tool(
    name: &str,
    description: String,
    schema: serde_json::Value,
    annotations: ToolAnnotations,
    sink: Arc<dyn ToolSink>,
    secret: [u8; 32],
) -> anyhow::Result<DynamicTool> {
    let tool_name =
        ToolName::new(name).map_err(|err| anyhow!("invalid tool name {name:?}: {err}"))?;
    let tool_label = name.to_string();
    Ok(DynamicTool::new_with_context(
        tool_name,
        description,
        schema,
        move |context: &mut ToolContext, args: serde_json::Value| {
            let sink = Arc::clone(&sink);
            let tool = tool_label.clone();
            Box::pin(async move {
                let scope: RunScope = context.require().map_err(|err| {
                    ToolExecutionError::other(format!(
                        "guarded tool dispatch is missing its run scope: {err}"
                    ))
                })?;
                let serde_json::Value::Object(mut input) = args else {
                    return Err(ToolExecutionError::invalid_args(format!(
                        "{tool} expects a JSON object of arguments"
                    )));
                };
                // The scope always wins: both reserved fields in the
                // model's arguments are replaced before the guard sees
                // them. The MAC is not model-visible and is bound to the
                // scope's task id.
                input.insert(
                    TASK_ID_FIELD.to_owned(),
                    serde_json::Value::String(scope.task_id.to_string()),
                );
                input.insert(
                    SCOPE_MAC_FIELD.to_owned(),
                    serde_json::Value::String(task_mac(&secret, scope.task_id)),
                );
                let request = ToolCallRequest {
                    tool,
                    input: serde_json::Value::Object(input),
                };
                match sink.execute(scope.task_id, scope.intent_id, request).await {
                    Ok(ToolCallOutcome::Allowed { output }) => Ok(ToolOutput::json(output)),
                    Ok(ToolCallOutcome::Denied { reason }) => {
                        Err(ToolExecutionError::permission_denied(reason))
                    }
                    Ok(ToolCallOutcome::Pending { approval_id }) => {
                        Err(ToolExecutionError::other(format!(
                            "tool call is parked behind approval {approval_id}; \
                                 approvals must block inside the tool call"
                        )))
                    }
                    Err(err) => Err(ToolExecutionError::other(err.to_string())),
                }
            })
        },
    )
    .with_annotations(annotations))
}


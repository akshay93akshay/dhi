    /// Records every call it sees and replays one scripted outcome.
    #[derive(Default)]
    struct FakeSink {
        calls: Mutex<Vec<(Uuid, Uuid, ToolCallRequest)>>,
        outcome: Mutex<Option<anyhow::Result<ToolCallOutcome>>>,
    }

    impl FakeSink {
        fn allowing(output: serde_json::Value) -> Self {
            Self::scripted(Ok(ToolCallOutcome::Allowed { output }))
        }

        fn denying(reason: &str) -> Self {
            Self::scripted(Ok(ToolCallOutcome::Denied {
                reason: reason.to_owned(),
            }))
        }

        fn pending() -> Self {
            Self::scripted(Ok(ToolCallOutcome::Pending {
                approval_id: Uuid::new_v4(),
            }))
        }

        fn scripted(outcome: anyhow::Result<ToolCallOutcome>) -> Self {
            Self {
                calls: Mutex::new(Vec::new()),
                outcome: Mutex::new(Some(outcome)),
            }
        }

        fn calls(&self) -> Vec<(Uuid, Uuid, ToolCallRequest)> {
            self.calls.lock().unwrap().clone()
        }
    }

    #[async_trait]
    impl ToolSink for FakeSink {
        async fn execute(
            &self,
            task_id: Uuid,
            intent_id: Uuid,
            request: ToolCallRequest,
        ) -> anyhow::Result<ToolCallOutcome> {
            self.calls
                .lock()
                .unwrap()
                .push((task_id, intent_id, request));
            self.outcome
                .lock()
                .unwrap()
                .take()
                .expect("the fake sink scripts exactly one call")
        }
    }

    /// The sink the host builds around the coding backend.
    struct BackendSink {
        backend: CodingBackend,
    }

    #[async_trait]
    impl ToolSink for BackendSink {
        async fn execute(
            &self,
            _task_id: Uuid,
            _intent_id: Uuid,
            request: ToolCallRequest,
        ) -> anyhow::Result<ToolCallOutcome> {
            let output = self.backend.execute(&request.tool, &request.input).await?;
            Ok(ToolCallOutcome::Allowed { output })
        }
    }

    fn fixture() -> (tempfile::TempDir, Arc<TaskContainers>, CodingTools) {
        let temp = tempfile::tempdir().unwrap();
        let containers = Arc::new(TaskContainers::local(temp.path()).unwrap());
        let tools = CodingTools::new(Arc::clone(&containers));
        (temp, containers, tools)
    }

    fn scope_context(task_id: Uuid, intent_id: Uuid) -> ToolContext {
        let mut context = ToolContext::new();
        context.insert(RunScope { task_id, intent_id }).unwrap();
        context
    }


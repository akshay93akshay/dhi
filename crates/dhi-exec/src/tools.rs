    #[tokio::test]
    async fn the_scope_task_id_reaches_the_sink_and_the_model_cannot_forge_it() {
        let (_temp, _workspaces, tools) = fixture();
        let sink = Arc::new(FakeSink::allowing(json!({ "ok": true })));
        let handle = ToolServer::new().run();
        tools.register_tools(&handle, sink.clone()).unwrap();

        let task_id = Uuid::new_v4();
        let intent_id = Uuid::new_v4();
        let forged_task = Uuid::new_v4();
        let forged_mac = tools.mac(forged_task);
        let mut context = scope_context(task_id, intent_id);
        let mut arguments = json!({ "path": "a.txt" });
        arguments[TASK_ID_FIELD] = json!(forged_task.to_string());
        arguments[SCOPE_MAC_FIELD] = json!(forged_mac.clone());

        let result = handle
            .toolset()
            .execute("read", arguments.to_string(), &mut context)
            .await;

        assert!(result.is_success(), "{result:?}");
        assert_eq!(result.output().as_json(), Some(&json!({ "ok": true })));

        let calls = sink.calls();
        assert_eq!(calls.len(), 1);
        let (seen_task, seen_intent, request) = &calls[0];
        assert_eq!((*seen_task, *seen_intent), (task_id, intent_id));
        assert_eq!(request.tool, "read");
        assert_eq!(
            request.input.get(TASK_ID_FIELD),
            Some(&json!(task_id.to_string())),
            "the scope's task id overwrites the model's"
        );
        assert_ne!(
            request.input.get(TASK_ID_FIELD),
            Some(&json!(forged_task.to_string()))
        );
        assert_eq!(
            request.input.get(SCOPE_MAC_FIELD),
            Some(&json!(tools.mac(task_id))),
            "the facade's task MAC overwrites the model's"
        );
        assert_ne!(request.input.get(SCOPE_MAC_FIELD), Some(&json!(forged_mac)));
        assert_eq!(request.input.get("path"), Some(&json!("a.txt")));
    }

